#!/usr/bin/env python3
"""make_driver.py -- turn the extracted CellphoneDB code cells into a runnable script.

Input  : cellchat_cells_extracted.py   (34 code cells, verbatim, produced by
                                        extract_dynamo_cells.py from the tutorial HTML)
Output : cellchat_cells_aswritten.py   (same cells + four documented patches)
Log    : patches_applied.txt           (one line per substitution, for the audit trail)

Why patches are needed at all: the tutorial is a notebook. Three of its cells contain IPython
magics that are not Python (`! pip install`, `%matplotlib inline` twice), and one cell ends with a
plotnine `ggplot` object as its *last expression* -- which a notebook renders through the display
hook and a plain script silently discards. Nothing else is touched: every other cell is byte-for-byte
the tutorial's.

usage: python make_driver.py
"""
import re

SRC = 'cellchat_cells_extracted.py'
DST = 'cellchat_cells_aswritten.py'
LOG = 'patches_applied.txt'

HEADER = '''#!/usr/bin/env python
# AUTO-GENERATED by make_driver.py from cellchat_cells_extracted.py (34 verbatim code cells
# extracted from scRNAseq-cellchat.html).  Regenerate with `python make_driver.py`; the
# substitutions are listed in patches_applied.txt and described here:
#
# @@NOTE  P1  cell 0   `! pip install cellphonedb`  -> neutralised.  The `!` magic is not Python, and
#         `pip install` into the shared, already-correct environment (cellphonedb 5.0.1,
#         ktplotspy 0.3.3) would upgrade numpy/scipy/pandas underneath a running analysis.
#         Registered as CPB-01.
# @@NOTE  P2  cell 2, 29   `%matplotlib inline` -> neutralised.  Magic, not Python; the harness
#         below already selects the Agg backend and captures every open figure after each cell.
# @@NOTE  H1  cells 31, 32   both cells END with a plotnine ggplot object (`kpy.plot_cpdb(...)` and
#         `p + facet_wrap(...)`), which a notebook displays through its repr hook and a script
#         silently discards.  They are assigned and handed to the harness's _save_gg(), which calls
#         .draw() -- plotnine draws onto a Figure that pyplot does not register, so the ordinary
#         _flush() sweep cannot see it.  Plot content is untouched.  Registered as CPB-02.
# @@NOTE  (no patch)  cells 6/18 hardcode relative paths (`data/cellphoneDB/...`,
#         `results/cellphoneDB/...`); the run directory supplies them via a symlink to the course
#         data, so the tutorial's paths work verbatim.  Registered as CPB-03 (portability).
#
# Deviations are applied to the CELL TEXT ONLY; the analysis parameters (threads=5, threshold=0.1,
# iterations=1000, pvalue=0.05, degs_analysis=False, separator='|', ...) are exactly as written.
'''

PATCHES = [
    # (regex, replacement, log-note)
    # H0: give the harness a plotnine-aware saver (it cannot live in the extracted file, which is
    # kept byte-identical to the notebook; see @@NOTE H1).
    (r'^_INLINE = \[\]$',
     '_INLINE = []\n'
     '\n'
     '\n'
     'def _save_gg(obj, cell, tag):\n'
     '    """Capture what a notebook would DISPLAY for a cell whose last expression is a plot.\n'
     '\n'
     '    plotnine renders through the notebook repr hook and draws onto a Figure that pyplot does\n'
     '    NOT register, so the _flush() sweep below cannot see it.  .draw() returns that Figure.\n'
     '    """\n'
     '    if obj is None:\n'
     '        print("[harness] cell %d returned None (no figure to capture)" % cell)\n'
     '        return\n'
     '    fig = obj.draw() if hasattr(obj, "draw") else obj\n'
     '    fig = getattr(fig, "figure", fig)\n'
     '    name = "inline_cell%02d_%s.png" % (cell, tag)\n'
     '    fig.savefig(os.path.join(_FIGDIR, name), dpi=200, bbox_inches="tight")\n'
     '    _INLINE.append(name)\n'
     '    print("[harness] wrote figure/%s" % name)',
     'H0 harness: added _save_gg() (plotnine-aware figure capture)'),
    (r'^! pip install cellphonedb$',
     '# [P1] `! pip install cellphonedb` removed -- see @@NOTE; env already has cellphonedb 5.0.1\n'
     'print("[P1] skipped: ! pip install cellphonedb (shared env already has 5.0.1)")',
     'P1 cell 0: ! pip install cellphonedb -> print + comment'),
    (r'^%matplotlib inline$',
     '# [P2] `%matplotlib inline` removed -- harness uses Agg and captures figures\npass',
     'P2 cell 2/29: %matplotlib inline -> pass'),
    (r'\nkpy\.plot_cpdb\(\n',
     '\n# [H1] capture the ggplot this cell returns (notebook renders it; a script drops it)\n'
     '_gg31 = kpy.plot_cpdb(\n',
     'H1 cell 31: kpy.plot_cpdb(...) -> assigned to _gg31'),
    (r'\n_flush\(31, "auto"\)',
     '\n_save_gg(_gg31, 31, "gg")\n_flush(31, "auto")',
     'H1 cell 31: _save_gg(_gg31, 31) inserted before the flush'),
    (r'\np \+ facet_wrap\("~ classification", ncol = 1\)\n',
     '\n# [H1] same for the faceted plot (p + facet_wrap(...))\n'
     '_p_faceted = p + facet_wrap("~ classification", ncol = 1)\n'
     '_save_gg(_p_faceted, 32, "gg")\n',
     'H1 cell 32: p + facet_wrap(...) -> assigned to _p_faceted and captured'),
]


def main():
    src = open(SRC, encoding='utf-8').read()
    n_p2 = len(re.findall(r'^%matplotlib inline$', src, re.M))
    applied = []
    out = src
    for pat, rep, note in PATCHES:
        out, n = re.subn(pat, rep, out, flags=re.M)
        if n == 0:
            raise SystemExit('patch did not apply: ' + note)
        applied.append('%s  (%d occurrence%s)' % (note, n, '' if n == 1 else 's'))

    # the harness banner in the extracted file says "do not hand-edit"; replace that line set
    out = out.replace(
        '# AUTO-EXTRACTED from the tutorial HTML by extract_dynamo_cells.py -- do not hand-edit\n'
        '# the cell bodies; apply deviations as a documented patch at the top instead.\n', '')
    out = HEADER + out

    open(DST, 'w', encoding='utf-8').write(out)
    with open(LOG, 'w', encoding='utf-8') as f:
        f.write('# patches applied by make_driver.py\n')
        f.write('# source: %s (%d code cells)\n' % (SRC, src.count('# ===================== cell ')))
        for a in applied:
            f.write(a + '\n')
        f.write('cells with %%matplotlib inline: %d\n' % n_p2)
    print('\n'.join(applied))
    print('->', DST)


if __name__ == '__main__':
    main()
